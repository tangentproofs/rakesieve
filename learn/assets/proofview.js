// Proof view: English commentary beside the real Lean proof, step by step. Two layouts, switched
// with a toggle and remembered in localStorage (separately for wide and narrow screens):
//   panes   — English steps (left) and the whole Lean proof (right), each pane scrolling on its own;
//             selecting or hovering a step on either side highlights its counterpart and scrolls it
//             into view. Default on wide screens.
//   outline — the English steps as an outline; each shows a one-line Lean preview and opens its Lean
//             inline when selected. On wide screens a minimap of the whole proof sits alongside.
//             Default on narrow screens (< 800px), where two panes are cramped.
// "Show all Lean" switches every Lean segment between compact (first line + "⋯ N more lines") and full.
// Data: data/proofs.json, generated by tools/build_proof_steps.mjs from site/proofs/*.yml.
import { wrapLeanLines } from "./leanlines.js";

export const MODES = ["panes", "outline"];
export const MODE_LABEL = { panes: "Linked panes", outline: "Outline" };
export const NARROW_PX = 800;

/** Mode to use: the stored choice for this screen class, else panes (wide) / outline (narrow). */
export function pickMode(stored, narrow) {
  const v = stored && typeof stored === "object" ? stored[narrow ? "narrow" : "wide"] : null;
  return MODES.includes(v) ? v : narrow ? "outline" : "panes";
}
/** Compact form of a Lean segment: its first line and how many lines are hidden. */
export function foldLean(text) {
  const lines = String(text).split("\n");
  return { first: lines[0], more: lines.length - 1 };
}
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const BADGE = {
  explainer: `<span class="pv-src ok" title="English from this node's reviewed explainer">explainer</span>`,
  comment: `<span class="pv-src ok" title="English from a comment in the Lean source">Lean comment</span>`,
  draft: `<span class="pv-src draft" title="Not reviewed yet: check it against the Lean">draft</span>`,
};

/** Mount the proof view for `proof` into `el`.
 *  opts: { highlight(src) → html, nodeHref(id), sourceUrl(file, from, to), githubSourceUrl(file, from, to), storageKey }
 *  Line links open the on-site rendered source (sourceUrl); GitHub is only the small secondary link. */
export function mountProofView(el, proof, opts) {
  const { highlight, nodeHref, sourceUrl, githubSourceUrl, storageKey } = opts;
  const segs = proof.segments;
  const narrowQ = typeof matchMedia === "function" ? matchMedia(`(max-width: ${NARROW_PX}px)`) : { matches: false };
  const load = () => { try { return JSON.parse(localStorage.getItem(storageKey)) || {}; } catch { return {}; } };
  let mode = pickMode(load(), narrowQ.matches);
  let compact = true, sel = -1;
  const opened = new Set();
  const lean = (src) => wrapLeanLines(highlight(src), src);
  const lines = (s) => `<a class="pv-lines" href="${sourceUrl(proof.file, s.from, s.to)}" title="open these lines in the highlighted source">L${s.from}${s.to > s.from ? `–${s.to}` : ""}</a>`;
  const en = (s, k) => `
    <div class="pv-title"><span class="pv-num">${k + 1}</span>${esc(s.title)}${s.hard ? ` <span class="pv-hard">hard</span>` : ""}</div>
    ${s.note ? `<div class="pv-note">${esc(s.note)}</div>` : ""}
    <div class="pv-meta">${BADGE[s.src] || ""} ${lines(s)}${(s.uses || []).map((u) => ` <a class="pv-use" href="${nodeHref(u)}">${esc(u.split(".").pop())}</a>`).join("")}</div>`;
  const leanBlock = (s, k, open) => {
    const f = foldLean(s.lean);
    if (open || !f.more) return `<pre class="lean wrap pv-lean">${lean(s.lean)}</pre>`;
    return `<pre class="lean wrap pv-lean compact">${lean(f.first)}<button type="button" class="pv-more" data-open="${k}">⋯ ${f.more} more line${f.more > 1 ? "s" : ""}</button></pre>`;
  };
  const isOpen = (k) => !compact || opened.has(k);

  function render() {
    const head = `
      <div class="pv-bar">
        <div class="pv-toggle" role="group" aria-label="Proof layout">${MODES.map((m) => `<button type="button" data-mode="${m}" class="${m === mode ? "on" : ""}" aria-pressed="${m === mode}">${MODE_LABEL[m]}</button>`).join("")}</div>
        <button type="button" class="pv-all">${compact ? "Show all Lean" : "Compact Lean"}</button>
        <span class="small muted">${segs.length} steps · <span class="srclink"><a href="${sourceUrl(proof.file, proof.from, proof.to)}" title="open the whole proof in the highlighted source">${esc(proof.file.split("/").pop())} lines ${proof.from}–${proof.to}</a>${githubSourceUrl ? `<a class="gh" href="${githubSourceUrl(proof.file, proof.from, proof.to)}" target="_blank" rel="noopener" title="the same lines on GitHub">GitHub ↗</a>` : ""}</span></span>
      </div>`;
    let body;
    if (mode === "panes") {
      body = `<div class="pv-panes">
        <div class="pv-pane pv-en">${segs.map((s, k) => `<div class="pv-step${k === sel ? " sel" : ""}" data-k="${k}" tabindex="0">${en(s, k)}</div>`).join("")}</div>
        <div class="pv-pane pv-code">${segs.map((s, k) => `<div class="pv-seg${k === sel ? " sel" : ""}" data-k="${k}"><span class="pv-tag">${k + 1}</span>${leanBlock(s, k, isOpen(k))}</div>`).join("")}</div>
      </div>`;
    } else {
      body = `<div class="pv-outline-wrap"><ol class="pv-outline">${segs.map((s, k) => `
        <li class="pv-step${k === sel ? " sel" : ""}" data-k="${k}" tabindex="0">${en(s, k)}
          ${k === sel || isOpen(k) ? leanBlock(s, k, true) : `<div class="pv-peek"><code>${esc(foldLean(s.lean).first.trim())}</code>${foldLean(s.lean).more ? ` <span class="muted">+${foldLean(s.lean).more}</span>` : ""}</div>`}
        </li>`).join("")}</ol>
        <aside class="pv-minimap" aria-label="The whole Lean proof">${segs.map((s, k) => `<div class="pv-mm${k === sel ? " sel" : ""}" data-k="${k}" title="${k + 1}. ${esc(s.title)}"><pre>${esc(s.lean)}</pre></div>`).join("")}</aside></div>`;
    }
    el.innerHTML = head + body;
    wire();
  }
  function select(k, from) {
    sel = mode === "outline" && sel === k && from === "en" ? -1 : k;
    render();
    if (sel < 0) return;
    const scroll = (q) => el.querySelector(q)?.scrollIntoView({ block: "nearest", behavior: "smooth" });
    if (mode === "panes") { if (from !== "code") scroll(`.pv-seg[data-k="${sel}"]`); if (from !== "en") scroll(`.pv-step[data-k="${sel}"]`); }
    else scroll(`.pv-step[data-k="${sel}"]`); // opening a step can move it when the previous one closes
  }
  function wire() {
    el.querySelectorAll("[data-mode]").forEach((b) => b.onclick = () => {
      mode = b.dataset.mode;
      const st = load(); st[narrowQ.matches ? "narrow" : "wide"] = mode;
      try { localStorage.setItem(storageKey, JSON.stringify(st)); } catch { /* private mode: not remembered */ }
      render();
    });
    el.querySelector(".pv-all").onclick = () => { compact = !compact; opened.clear(); render(); };
    el.querySelectorAll(".pv-more").forEach((b) => b.onclick = (e) => { e.stopPropagation(); opened.add(+b.dataset.open); render(); });
    const on = (q, from) => el.querySelectorAll(q).forEach((x) => {
      x.addEventListener("click", (e) => { if (e.target.closest("a, button") || (from === "code" && getSelection()?.toString())) return; select(+x.dataset.k, from); });
      x.addEventListener("keydown", (e) => { if (e.key === "Enter" && !e.target.closest("a, button")) select(+x.dataset.k, from); });
    });
    on(".pv-step", "en"); on(".pv-seg", "code"); on(".pv-mm", "map");
    if (mode === "panes") el.querySelectorAll(".pv-step, .pv-seg").forEach((x) => {
      x.addEventListener("mouseenter", () => el.querySelectorAll(`[data-k="${x.dataset.k}"]`).forEach((y) => y.classList.add("hov")));
      x.addEventListener("mouseleave", () => el.querySelectorAll(".hov").forEach((y) => y.classList.remove("hov")));
    });
  }
  render();
  return { select: (k) => select(k, "api"), setCompact: (c) => { compact = c; opened.clear(); render(); }, get mode() { return mode; } };
}
